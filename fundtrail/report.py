"""Render a markdown incident report from a trace graph."""

from __future__ import annotations

from collections import defaultdict
from typing import Any

EXPLORERS = {
    "ethereum": "https://etherscan.io", "arbitrum": "https://arbiscan.io",
    "optimism": "https://optimistic.etherscan.io", "base": "https://basescan.org",
    "bsc": "https://bscscan.com", "polygon": "https://polygonscan.com",
}


def _short(a: str) -> str:
    return f"{a[:8]}…{a[-4:]}" if len(a) > 14 else a


def _fmt(x: float) -> str:
    return f"{x:,.4f}".rstrip("0").rstrip(".")


def render_report(graph: dict[str, Any], title: str | None = None,
                  max_rows: int = 40) -> str:
    chain = graph["chain"]
    exp = EXPLORERS.get(chain)
    nodes = {n["address"]: n for n in graph["nodes"]}

    def link_addr(a: str) -> str:
        n = nodes.get(a, {})
        name = f" ({n['label']})" if n.get("label") else ""
        return f"[{_short(a)}]({exp}/address/{a}){name}" if exp else f"`{a}`{name}"

    def link_tx(h: str) -> str:
        return f"[{_short(h)}]({exp}/tx/{h})" if exp else f"`{h}`"

    edges = graph["edges"]
    lines = [f"# {title or 'Incident trace report'}", "",
             "_Generated by fundtrail (early prototype). Check every finding against a "
             "block explorer before acting on it._", "",
             "## Summary", "",
             f"- Chain: {chain}",
             f"- Start address: {link_addr(graph['start'])}",
             f"- Addresses: {len(graph['nodes'])}, transfers: {len(edges)}",
             f"- Parameters: `{_params(graph.get('params', {}))}`", ""]

    totals: dict[tuple[str, str], float] = defaultdict(float)
    for e in edges:
        dst = nodes.get(e["dst"], {})
        if dst.get("kind"):
            totals[(dst["kind"], e.get("symbol") or e["asset"])] += e["amount"]
    lines += ["## Flows into labelled mixers / bridges", ""]
    if totals:
        for (kind, sym), amt in sorted(totals.items()):
            lines.append(f"- {kind}: {_fmt(amt)} {sym}")
        lines.append("")
        for n in graph.get("flagged", []):
            lines.append(f"- {link_addr(n['address'])}: {n['kind']}")
    else:
        lines.append("- None found in the traced window.")
    lines.append("")

    lines += ["## Largest transfers", "",
              "| Hop | From | To | Amount | Tx | Block |", "|---|---|---|---|---|---|"]
    for e in sorted(edges, key=lambda e: e["amount"], reverse=True)[:max_rows]:
        lines.append(f"| {e['hop']} | {link_addr(e['src'])} | {link_addr(e['dst'])} | "
                     f"{_fmt(e['amount'])} {e.get('symbol') or _short(e['asset'])} | "
                     f"{link_tx(e['tx'])} | {e['block']} |")
    if len(edges) > max_rows:
        lines.append(f"\n_{len(edges) - max_rows} smaller transfers omitted; see the JSON graph._")
    lines.append("")

    lines += ["## Addresses where tracing stopped", ""]
    stopped = [n for n in graph["nodes"] if n.get("stop_reason")]
    for n in stopped[:max_rows]:
        lines.append(f"- {link_addr(n['address'])}: {n['stop_reason']}")
    if not stopped:
        lines.append("- None.")
    lines.append("")

    extra = graph.get("summary_extra") or {}
    if extra.get("onchain_messages"):
        lines += ["## On-chain messages", ""]
        for tx, msg in extra["onchain_messages"].items():
            lines.append(f"- {link_tx(tx)}: \"{msg}\"")
        lines.append("")
    if extra.get("seller_B_tornado"):
        s = extra["seller_B_tornado"]
        lines += ["## Not shown as edges", "",
                  f"- Seller B Tornado deposits: {s.get('count')} txs, "
                  f"{s.get('total_bnb')} BNB ({s.get('first')} to {s.get('last')})", ""]

    lines += ["## Caveats", ""]
    for w in graph.get("warnings", []):
        lines.append(f"- {w}")
    lines += ["- Contract-internal native transfers are not traced (no trace API used).",
              "- Labels come from a bundled list; an unlabelled address is not proof "
              "that it is a private wallet.", ""]
    return "\n".join(lines)


def _params(p: dict[str, Any]) -> str:
    return ", ".join(f"{k}={v}" for k, v in p.items() if k != "method")
